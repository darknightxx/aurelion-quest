// procedural math questions by difficulty
function genMath(d) {
  let q, a;
  const r = (x, y) => randi(x, y);
  const t = Math.random();
  if (d <= 1) {
    if (t < .35) { const x = r(5, 60), y = r(3, 39); q = `${x} + ${y} = ?`; a = x + y; }
    else if (t < .6) { const x = r(20, 99), y = r(2, x - 1); q = `${x} − ${y} = ?`; a = x - y; }
    else { const x = r(2, 9), y = r(2, 9); q = `${x} × ${y} = ?`; a = x * y; }
  } else if (d === 2) {
    if (t < .3) { const x = r(11, 49), y = r(2, 9); q = `${x} × ${y} = ?`; a = x * y; }
    else if (t < .55) { const y = r(3, 12), a0 = r(4, 15); q = `${a0 * y} ÷ ${y} = ?`; a = a0; }
    else if (t < .8) { const x = r(2, 9), y = r(2, 9), z = r(2, 20); q = `${z} + ${x} × ${y} = ?`; a = z + x * y; }
    else { const x = r(120, 900), y = r(45, 300); q = `${x} + ${y} = ?`; a = x + y; }
  } else {
    if (t < .25) { const p = pick([10, 20, 25, 50, 75]), b = pick([40, 80, 120, 200, 360, 400]); q = `${p}% ของ ${b} เท่ากับเท่าใด`; a = p * b / 100; }
    else if (t < .5) { const x = r(11, 25); q = `${x}² = ?`; a = x * x; }
    else if (t < .75) { const x = r(2, 15), m = r(2, 9), c = r(1, 20); q = `ถ้า ${m}x + ${c} = ${m * x + c} แล้ว x = ?`; a = x; }
    else { const x = r(3, 12), y = r(3, 12), z = r(2, 6); q = `(${x} + ${y}) × ${z} = ?`; a = (x + y) * z; }
  }
  const opts = new Set([a]);
  const spread = Math.max(3, Math.round(Math.abs(a) * 0.15));
  let guard = 0;
  while (opts.size < 4 && guard++ < 60) { let w = a + (Math.random() < .5 ? -1 : 1) * randi(1, spread); if (Math.random() < .25) w = a + pick([-10, 10, 1, -1]); if (w >= 0 && w !== a) opts.add(w); }
  while (opts.size < 4) opts.add(a + opts.size * 7);
  const fmt = n => Number.isInteger(n) ? n.toLocaleString('en-US') : String(n);
  return { cat: 'math', q, a: fmt(a), opts: [...opts].map(fmt), gen: true };
}

